const shop: MapShop = {id: 7, latitude: 9.03, longitude: 39.7, locationMode: 'area', handle: 'fixture', name: 'Fixture', description: 'not for tile provider', heroImagePath: '/image', city: 'City', region: 'Region'};
const displayed = mapDisplayLocation(shop);
assert.deepEqual(shopCoordinate(shop), [displayed.longitude, displayed.latitude]);
assert.deepEqual(shopCoordinate({...shop, locationMode: 'storefront', latitude: 0, longitude: 0}), [0, 0]);
const features = shopFeatures([shop, shop, {...shop, id: 8, latitude: NaN}, {...shop, id: 9, longitude: 181}]);
assert.equal(features.features.length, 1);
assert.deepEqual(features.features[0].properties, {shopId: 7});
assert.equal(JSON.stringify(features).includes('not for tile provider'), false);
assert.deepEqual(shopFeatures([shop, {...shop, id: 8}]).features[0], shopFeatures([shop]).features[0]);
assert.equal(selectedMapShop(7, [shop]), shop);
for (const id of [8, '7', null, {id: 7}]) assert.equal(selectedMapShop(id, [shop]), undefined);
assert.equal(selectedMapShop(7, []), undefined);
assert.equal(nextMapZoom(19, 1), 13);
assert.equal(nextMapZoom(3, -1), 2);
assert.equal(nextMapZoom(1, -1), 1);
assert.equal(nextMapZoom(6, 1), 7);
assert.equal(nextMapZoom(NaN, 1), 7);
assert.deepEqual(osmStyle.sources.osm, {type: 'raster', tiles: ['https://tile.openstreetmap.org/{z}/{x}/{y}.png'], tileSize: 256, maxzoom: 19, attribution: '© OpenStreetMap contributors'});
console.log('Native map: validated public projection, stable city placement, exact/zero coordinates, current-result selection and zoom bounds pass.');
const groupBase={...shop,locationMode:'storefront' as const};
const other = {...groupBase, id: 8, isLive: true};
const featured = {...groupBase, id: 9, isFeatured: true};
const shops = [groupBase, other, featured];
const index = markerIndex(shops);
const bounds: [number,number,number,number] = [30, 0, 50, 20];
const clusters = visibleMarkers(index, shops, [], bounds, 6);
assert.equal(clusters.length, 1);
assert.equal(clusters[0].kind, 'cluster');
assert.equal(clusters[0].count, 3);
assert.equal(clusters[0].presence, 'featured');
assert.deepEqual(clusters[0].shops?.map(s=>s.id),[7,8,9]);
const group = {key: 'city', city: 'City', latitude: 9.03, longitude: 39.7, showroomIds: [7,8,9,99]};
const nearby = visibleMarkers(index, shops, [group], bounds, 14);
assert.equal(nearby.length, 1,'Fixed current members never split as zoom changes');
assert.equal(nearby[0].kind,'cluster');
assert.deepEqual(nearby[0].shops?.map(marker=>marker.id),[7,8,9]);
assert.deepEqual(visibleMarkers(index, shops, [group], [0,0,1,1], 14), []);
const filtered = visibleMarkers(markerIndex([shop]), [shop], [group], bounds, 14);
assert.equal(filtered.length,1);
assert.equal(filtered[0].kind,'shop','An isolated city-area business uses the named shop marker, never a numbered1 circle');
assert.equal(filtered[0].shop,shop);assert.equal(filtered[0].shop?.name,'Fixture');assert.equal(filtered[0].shops,undefined);
assert.deepEqual(filtered[0].center,[shop.longitude,shop.latitude]);assert.deepEqual(filtered[0].anchor,[shop.longitude,shop.latitude],'The shop stays at its canonical city point without fabricated storefront coordinates');
assert.equal(filtered[0].expansionZoom,undefined,'An isolated shop opens its business preview directly');
assert.equal(visibleMarkers(markerIndex([shop,shop]), [shop], [], bounds, 6).length, 1);
assert.equal(markerNameLines('A very long business name with many extra words').split('\n').length, 3);
assert.ok(markerNameLines('A very long business name with many extra words').endsWith('…'));
console.log('Marker parity: persistent viewport clustering, current group selection, filtered membership, presence and bounded labels pass.');

